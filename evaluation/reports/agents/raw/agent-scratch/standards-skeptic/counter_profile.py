cases = json.load(open(WT + "/conformance/v0_2/semantic-cases.json"))

# --- support_sets as PROV pattern: each alternative path = one prov:specializationOf of K,
# each specialization generated by one activity that prov:used all members (joint requirement).
def to_prov(case):
    doc = {"entity": {"K": {}}, "specializationOf": {}, "wasGeneratedBy": {}, "used": {}}
    for i, s in enumerate(case["support_sets"]):
        k_i, act = f"K_path{i}", f"derive{i}"
        doc["entity"][k_i] = {}
        doc["specializationOf"][f"_:s{i}"] = {"prov:specificEntity": k_i, "prov:generalEntity": "K"}
        doc["wasGeneratedBy"][f"_:g{i}"] = {"prov:entity": k_i, "prov:activity": act}
        for j, src in enumerate(s):
            doc["used"][f"_:u{i}_{j}"] = {"prov:activity": act, "prov:entity": src}
    return doc

def atms_label(doc):  # label of K = set of environments (why-provenance witness basis)
    acts = {}
    for u in doc["used"].values(): acts.setdefault(u["prov:activity"], set()).add(u["prov:entity"])
    gen = {g["prov:entity"]: g["prov:activity"] for g in doc["wasGeneratedBy"].values()}
    return [acts[gen[s["prov:specificEntity"]]] for s in doc["specializationOf"].values()]

def profile_invalidation(case):
    label = atms_label(to_prov(case)); removed = set(case["removed_sources"])
    material_removed = bool(set(case["all_sources"]) & removed)
    surviving = any(not (env & removed) for env in label)   # ATMS: node IN iff some environment holds
    return {"current_support_exists": surviving,
            "action": "none" if not material_removed else ("recompute" if surviving else "invalidate"),
            "historical_lineage_preserved": True}            # PROV is append-only: wasInvalidatedBy, never delete

ok = 0
for c in cases["dependency_invalidation"]:
    a, b = profile_invalidation(c), rcp.dependency_invalidation_result(c)
    ok += a == b == c["expected"]; print("invalidation", c["id"], "PROV+ATMS==RCP:", a == b, "==expected:", a == c["expected"])

# --- restriction inheritance as ODRL: child asset obtained by odrl:derive with duty odrl:nextPolicy(parent);
# combined with odrl:conflict odrl:prohibit; purposes as odrl:constraint purpose isAnyOf; retention as dateTime/elapsedTime lteq.
def odrl_effective(parents):
    pol = {"permission": None, "prohibition": set(), "elapsedTime_lteq": None}
    for p in parents:
        purposes = set(p["allowed_purposes"])
        pol["permission"] = purposes if pol["permission"] is None else pol["permission"] & purposes  # all constraints must hold
        for act in ("external_processing", "training"):
            if p[act] == "deny": pol["prohibition"].add(act)                                        # prohibit wins
        t = p["retention_max_seconds"]; pol["elapsedTime_lteq"] = t if pol["elapsedTime_lteq"] is None else min(t, pol["elapsedTime_lteq"])
    return pol
def odrl_child_ok(case):
    if case.get("declassification_basis") and not case.get("declassification_profile"): return False
    e, ch = odrl_effective(case["parents"]), case["child"]
    if not set(ch["allowed_purposes"]) <= e["permission"]: return False
    if any(ch[a] != "deny" for a in e["prohibition"]): return False
    return ch["retention_max_seconds"] <= e["elapsedTime_lteq"]
for c in cases["policy_projection"]:
    a, b = odrl_child_ok(c), rcp.policy_projection_valid(c)
    ok += a == b == c["expected_valid"]; print("policy", c["id"], "ODRL==RCP:", a == b)

# --- source_access: AuthZEN evaluation on the source resource is independent of the child resource
for c in cases["source_access"]:
    authzen = {"decision": c.get("source_access") == "allow" and c.get("source_state") == "active"}
    ok += authzen["decision"] == rcp.source_access_allowed(c) == c["expected_source_access"]
    print("source-access", c["id"], "AuthZEN(source)==RCP:", authzen["decision"] == rcp.source_access_allowed(c))

# --- non-independent evidence: PROV hadPrimarySource lets the profile collapse same-origin witnesses; RCP cannot.
case = {"all_sources": ["mail:1", "crm:7"], "support_sets": [["mail:1"], ["crm:7"]], "removed_sources": ["mail:1"]}
primary = {"crm:7": "mail:1"}  # crm:7 prov:hadPrimarySource mail:1
removed_closure = set(case["removed_sources"]) | {s for s, p in primary.items() if p in case["removed_sources"]}
print("same-origin: RCP oracle ->", rcp.dependency_invalidation_result(case)["action"],
      "| PROV hadPrimarySource-aware ->", profile_invalidation({**case, "removed_sources": sorted(removed_closure)})["action"])
print("matched", ok, "of", len(cases["dependency_invalidation"]) + len(cases["policy_projection"]) + len(cases["source_access"]))
